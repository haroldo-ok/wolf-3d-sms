"""Builds all ROM data: gen/data.bin (banks from DATA_FIRST_BANK) + gen/assets.h
+ gen/assets.inc + gen/assets_tab.c"""
import os, sys, re, hashlib
from packer import Packer
HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, '..', 'gen')
CACHE = os.path.join(GEN, 'cache')
DATA_FIRST_BANK = int(os.environ.get('DATA_FIRST_BANK', '16'))
os.makedirs(GEN, exist_ok=True)
os.makedirs(CACHE, exist_ok=True)

H = []      # header lines
C = []      # bank-0 table source lines
MODULES = ['wl_view.py', 'wl_assets.py', 'wl_maps.py', 'render_gen.py', 'sms.py', 'wolfdata.py',
           'wl_pics.py', 'wl_audio.py', 'wl_text.py', 'wl_hud.py', 'wl_states.py', 'wl_weapons.py', 'scrcore.py', 'wl_scr.py', 'wl_gfx.py']


def cached(key, fn):
    """cache expensive conversions keyed on the tool sources"""
    h = hashlib.md5(key.encode())
    for f in MODULES:
        p = os.path.join(HERE, f)
        if os.path.exists(p):
            h.update(open(p, 'rb').read())
    path = os.path.join(CACHE, h.hexdigest() + '.bin')
    if os.path.exists(path):
        return open(path, 'rb').read()
    d = fn()
    open(path, 'wb').write(d)
    return d


def main():
    pk = Packer(DATA_FIRST_BANK)
    import wl_assets, wl_maps
    wl_assets.build_render(pk, H, C)
    d, pal, m = wl_assets.data()
    import sprnames
    for i, n in enumerate(sprnames.sprite_names(wl_assets.SRCDIR)):
        H.append('#define %s %d' % (n, i))
    import wl_names
    snd, mus = wl_names.audio_names()
    for n, v in snd + mus:
        H.append('#define %s %d' % (n, v))
    for n, v in wl_names.gfx_names():
        H.append('#define %s %d' % (n, v))
    # cart RAM layout (single source: src/cartram.h) for the assembler
    for l in open(os.path.join(HERE, '..', 'src', 'cartram.h')):
        mm = re.match(r'#define (CR_\w+)\s+(0x[0-9A-Fa-f]+)', l)
        if mm:
            H.append('#define %s %s' % (mm.group(1), mm.group(2)))
    wl_maps.build(pk, H, C, d)
    for name in ('wl_hud', 'wl_pics', 'wl_text', 'wl_audio'):
        if os.path.exists(os.path.join(HERE, name + '.py')):
            mod = __import__(name)
            mod.build(pk, H, C, d, cached)
    nb = pk.write(os.path.join(GEN, 'data.bin'))
    H.append('#define DATA_FIRST_BANK %d' % DATA_FIRST_BANK)
    H.append('#define DATA_NUM_BANKS %d' % nb)
    with open(os.path.join(GEN, 'assets.h'), 'w') as f:
        f.write('/* generated by tools/build_assets.py */\n#ifndef ASSETS_H\n#define ASSETS_H\n#include "hw.h"\n')
        f.write('\n'.join(H) + '\n#endif\n')
    with open(os.path.join(GEN, 'assets.inc'), 'w') as f:
        f.write(';; generated by tools/build_assets.py\n')
        for l in H:
            mm = re.match(r'#define (\w+) (0x[0-9A-Fa-f]+|\d+)$', l)
            if mm:
                f.write('%s = %s\n' % (mm.group(1), mm.group(2)))
    with open(os.path.join(GEN, 'assets_tab.c'), 'w') as f:
        f.write('/* generated by tools/build_assets.py */\n#include "assets.h"\n')
        f.write('\n'.join(C) + '\n')
    with open(os.path.join(GEN, 'data_banks.txt'), 'w') as f:
        f.write('%d %d\n' % (DATA_FIRST_BANK, nb))
    print('data banks', nb, '(ROM', (DATA_FIRST_BANK + nb) * 16, 'KB)')


if __name__ == '__main__':
    main()
