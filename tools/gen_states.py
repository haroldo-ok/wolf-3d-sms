"""Moves every actor state of the game sources into one bank-0 table.

The game code is spread over switchable banks, so the states (read by all of
it) live in bank 0 as `states[]`; `s_name` becomes a macro for `states[i]`.
Think and action routines are referred to by number and called through
think_call() / action_call() (bank 0), which make the banked calls.

Usage: gen_states.py SRCDIR OUTDIR   (writes states.c, states.h)
"""
import re, sys, os

STATE_RE = re.compile(r'^\s*const\s+statetype\s+(\w+)\s*=\s*\{([^}]*)\}\s*;', re.M)


def parse(files):
    states = []         # (name, rotate, shape, tics, think, action, next)
    for fn in files:
        src = open(fn).read()
        for m in STATE_RE.finditer(src):
            f = [x.strip() for x in m.group(2).split(',')]
            assert len(f) == 6, m.group(0)
            states.append((m.group(1), f[0], f[1], f[2], f[3], f[4], f[5].lstrip('&')))
    return states


def strip_states(src):
    """remove state definitions and extern state declarations from a source"""
    src = STATE_RE.sub('', src)
    src = re.sub(r'^\s*extern\s+const\s+statetype\s+[^;]*;\s*$', '', src, flags=re.M)
    return src


def main(srcdir, outdir, files):
    states = parse([os.path.join(srcdir, f) for f in files])
    index = {s[0]: i for i, s in enumerate(states)}
    thinks, actions = [], []
    for s in states:
        for lst, v in ((thinks, s[4]), (actions, s[5])):
            if v != 'NULL' and v not in lst:
                lst.append(v)

    def ref(n):
        if n == 'NULL':
            return 'NULL'
        return '&states[%d]' % index[n]

    h = ['/* generated by tools/gen_states.py */', '#ifndef STATES_H', '#define STATES_H', '']
    h.append('#define NUMSTATES %d' % len(states))
    h.append('extern const statetype states[NUMSTATES];')
    h.append('#define STATE_INDEX(p) ((u16)((p) - states))')
    h.append('')
    h.append('enum {TH_NONE%s};' % ''.join(', TH_%s' % t for t in thinks))
    h.append('enum {AC_NONE%s};' % ''.join(', AC_%s' % t for t in actions))
    for t in thinks:
        h.append('void %s(objtype *ob) __banked;' % t)
    for t in actions:
        if t not in thinks:
            h.append('void %s(objtype *ob) __banked;' % t)
    h.append('void think_call(u8 think, objtype *ob);')
    h.append('u8 tpath_fast(objtype *ob);      /* fast.s: the common case of T_Path */')
    h.append('void action_call(u8 action, objtype *ob);')
    h.append('')
    for s in states:
        h.append('#define %s (states[%d])' % (s[0], index[s[0]]))
    h.append('#endif')
    open(os.path.join(outdir, 'states.h'), 'w').write('\n'.join(h) + '\n')

    c = ['/* generated by tools/gen_states.py */', '#include "def.h"', '',
         'const statetype states[NUMSTATES] = {']
    for s in states:
        th = 'TH_NONE' if s[4] == 'NULL' else 'TH_' + s[4]
        ac = 'AC_NONE' if s[5] == 'NULL' else 'AC_' + s[5]
        c.append('    {%s, %s, %s, %s, %s, %s},   /* %d %s */' % (s[1], s[2], s[3], th, ac, ref(s[6]), index[s[0]], s[0]))
    c.append('};')
    c.append('')
    c.append('void think_call(u8 think, objtype *ob)')
    c.append('{')
    c.append('    switch (think)')
    c.append('    {')
    # no banked call when the think routine would do nothing (T_Stand), or when bank 0 does its common case (T_Path)
    guard = {'T_Stand': 'SIGHT_SKIP(ob)', 'T_Path': 'tpath_fast(ob)'}
    for t in thinks:
        if t in guard:
            c.append('    case TH_%s: if (!%s) %s(ob); break;' % (t, guard[t], t))
        else:
            c.append('    case TH_%s: %s(ob); break;' % (t, t))
    c.append('    }')
    c.append('}')
    c.append('')
    c.append('void action_call(u8 action, objtype *ob)')
    c.append('{')
    c.append('    switch (action)')
    c.append('    {')
    for t in actions:
        c.append('    case AC_%s: %s(ob); break;' % (t, t))
    c.append('    }')
    c.append('}')
    open(os.path.join(outdir, 'states.c'), 'w').write('\n'.join(c) + '\n')
    print('states', len(states), 'thinks', len(thinks), 'actions', len(actions))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
